/**
 * @fileoverview Session calendars: calendar-aware bar boundaries mirroring
 * the market engine (`joseph.domain.sessions`).
 *
 * Crypto venues trade around the clock: their bars are aligned to the UTC
 * epoch (`CONTINUOUS_CALENDAR`, exactly the `identity.ts` timeframe math).
 * Exchange-listed instruments trade in sessions:
 *
 * - Intraday bars (seconds to 12h) start at the session open and repeat
 *   every timeframe until the close; the last bar of a session is cut short
 *   at the close (NYSE 1h: 09:30, 10:30 … 15:30-16:00).
 * - A daily bar is one session `[open, close)`.
 * - A weekly bar spans the sessions of one ISO week and a monthly bar the
 *   sessions of one calendar month, in the exchange's time zone.
 *
 * Time between sessions belongs to no bar. `floor` of such a time returns
 * the last bar that started before it; `shift` of a bar end counts from the
 * next bar start.
 *
 * The terminal works from session lists (`SessionList`, fetched from the
 * engine or generated by the DEMO provider). A `SessionCalendar` answers
 * from its list on the days the list covers and from the regular weekday
 * hours elsewhere, so arithmetic never fails while a list is loading; the
 * session cache replaces the calendar once the engine's list arrives.
 */
import type {
  CalendarId,
  InstrumentId,
  Timeframe,
  TradingSession,
} from './generated/contracts';
import {
  TIMEFRAME_MS,
  barsBetween as utcBarsBetween,
  floorToTimeframe,
  parseInstrumentId,
  shiftTimeframe,
  timeframeEnd,
} from './identity';

const MINUTE_MS = 60_000;
const DAY_MS = 86_400_000;

/** Days scanned for a neighbouring session before giving up (engine). */
const MAX_SCAN_DAYS = 60;

/** Days materialized around a lookup at a time. */
const TIMELINE_PAD_DAYS = 40;

/** Calendars with trading sessions (every calendar but `24x7`). */
export type ExchangeCalendarId = Exclude<CalendarId, '24x7'>;

/** Regular hours of an exchange calendar. */
export interface ExchangeHours {
  /** Calendar id. */
  readonly calendar: ExchangeCalendarId;
  /** IANA time zone of the exchange. */
  readonly timeZone: string;
  /** Regular open in minutes after local midnight. */
  readonly openMinute: number;
  /** Regular close in minutes after local midnight. */
  readonly closeMinute: number;
  /**
   * Prints up to this long after the close (a closing auction stamped at
   * the close) belong to the last bar of the session.
   */
  readonly closeGraceMs: number;
  /** Short market name for status text, e.g. `NYSE`. */
  readonly market: string;
}

