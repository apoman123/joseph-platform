/**
 * Whether a calendar id names an exchange calendar.
 * @param id Calendar id.
 * @return True for every calendar but `24x7`.
 */
export function isExchangeCalendar(id: CalendarId): id is ExchangeCalendarId {
  return id !== '24x7';
}

/**
 * Session calendar implied by an instrument id (engine
 * `instruments.calendar_code`): TWSE and TPEx → XTAI, Nasdaq/NYSE/Cboe → XNYS,
 * Treasury → USBOND, DEMO stocks and ETFs → XNYS, everything else `24x7`.
 * @param instrumentId Canonical instrument id.
 * @return Calendar id (`24x7` for unparseable ids).
 */
export function calendarIdForInstrumentId(instrumentId: string): CalendarId {
  let parts;
  try {
    parts = parseInstrumentId(instrumentId);
  } catch {
    return '24x7';
  }
  switch (parts.venue) {
    case 'twse':
    case 'tpex':
      return 'XTAI';
    case 'nasdaq':
    case 'nyse':
    case 'cboe':
      return 'XNYS';
    case 'treasury':
      return 'USBOND';
    case 'mock':
      return parts.marketType === 'stock' || parts.marketType === 'etf'
        ? 'XNYS'
        : '24x7';
    default:
      return '24x7';
  }
}

/**
 * Calendar of an instrument: the registry's `calendar` when known, else the
 * calendar implied by its id.
 * @param instrumentId Canonical instrument id.
 * @param instrument Registry entry, when loaded.
 * @return Calendar id.
 */
export function instrumentCalendarId(
  instrumentId: InstrumentId,
  instrument?: {calendar?: CalendarId | null} | null
): CalendarId {
  return instrument?.calendar ?? calendarIdForInstrumentId(instrumentId);
}

/** Bar-boundary arithmetic of one calendar (engine `BarCalendar`). */
export interface BarCalendar {
  /** Calendar id. */
  readonly id: CalendarId;
  /** Whether the market never closes (`24x7`). */
  readonly continuous: boolean;
  /** IANA time zone used to label times (`UTC` for `24x7`). */
  readonly timeZone: string;
  /**
   * Start of the bar at or before a time; between sessions, the last bar
   * that started before it.
   * @param timeframe Bar resolution.
   * @param tsMs UTC epoch milliseconds.
   * @return Bar start.
   */
  floor(timeframe: Timeframe, tsMs: number): number;
  /**
   * Exclusive end of the bar starting at `startMs` (the session close for
   * the last bar of a session).
   * @param timeframe Bar resolution.
   * @param startMs Aligned bar start.
   * @return Exclusive bar end.
   */
  endOf(timeframe: Timeframe, startMs: number): number;
  /**
   * Moves a bar start by whole bars; any other time (a bar end) counts from
   * the first bar start at or after it.
   * @param timeframe Bar resolution.
   * @param startMs Bar start or bar end.
   * @param bars Bars to move; negative moves back.
   * @return Start of the bar `bars` bars away.
   */
  shift(timeframe: Timeframe, startMs: number, bars: number): number;
  /**
   * Counts bar starts in `[startMs, endMs)`.
   * @param timeframe Bar resolution.
   * @param startMs Inclusive start.
   * @param endMs Exclusive end.
   * @return Number of bars (0 when empty).
   */
  barsBetween(timeframe: Timeframe, startMs: number, endMs: number): number;
  /**
   * Whether a time is exactly a bar start.
   * @param timeframe Bar resolution.
   * @param tsMs UTC epoch milliseconds.
   * @return True for a bar start.
   */
  isAligned(timeframe: Timeframe, tsMs: number): boolean;
  /**
   * Start of the newest bar fully closed at `asOfMs` (higher-timeframe
   * visibility rule).
   * @param timeframe Bar resolution.
   * @param asOfMs Evaluation time.
   * @return Bar start, or null when there is none.
   */
  lastClosedStart(timeframe: Timeframe, asOfMs: number): number | null;
  /**
   * Whether the market is in session at a time.
   * @param tsMs UTC epoch milliseconds.
   * @return True during a session (always for `24x7`).
   */
  isOpen(tsMs: number): boolean;
  /**
   * Sessions overlapping `[fromMs, toMs)`, in time order.
   * @param fromMs Inclusive start.
   * @param toMs Exclusive end.
   * @return Sessions (empty for `24x7`).
   */
  sessions(fromMs: number, toMs: number): TradingSession[];
  /**
   * Whether bars of `small` nest exactly in bars of `big`.
   * @param big Higher timeframe.
   * @param small Lower timeframe.
   * @return True when they tile.
   */
  contains(big: Timeframe, small: Timeframe): boolean;
}

/** Timeframes whose bars are whole sessions. */
const PERIODIC: ReadonlySet<Timeframe> = new Set<Timeframe>(['1d', '1w', '1M']);

/**
 * Whether a timeframe's bars are whole sessions (`1d`, `1w`, `1M`).
 * @param timeframe Bar resolution.
 * @return True for periodic timeframes.
 */
export function isPeriodicTimeframe(timeframe: Timeframe): boolean {
  return PERIODIC.has(timeframe);
}

/** Calendar of crypto venues and DEMO perpetuals: UTC epoch-aligned bars. */
class ContinuousCalendar implements BarCalendar {
  readonly id = '24x7' as const;
  readonly continuous = true;
  readonly timeZone = 'UTC';

  /**
   * See `BarCalendar.floor`.
   * @param timeframe Bar resolution.
   * @param tsMs Time.
   * @return Bar start.
   */
  floor(timeframe: Timeframe, tsMs: number): number {
    return floorToTimeframe(timeframe, tsMs);
  }

  /**
   * See `BarCalendar.endOf`.
   * @param timeframe Bar resolution.
   * @param startMs Bar start.
   * @return Bar end.
   */
  endOf(timeframe: Timeframe, startMs: number): number {
    return timeframeEnd(timeframe, startMs);
  }

  /**
   * See `BarCalendar.shift`.
   * @param timeframe Bar resolution.
   * @param startMs Bar start.
   * @param bars Bars to move.
   * @return Moved bar start.
   */
  shift(timeframe: Timeframe, startMs: number, bars: number): number {
    return shiftTimeframe(timeframe, startMs, bars);
  }

  /**
   * See `BarCalendar.barsBetween`.
   * @param timeframe Bar resolution.
   * @param startMs Start.
   * @param endMs End.
   * @return Bar count.
   */
  barsBetween(timeframe: Timeframe, startMs: number, endMs: number): number {
    return utcBarsBetween(timeframe, startMs, endMs);
  }

  /**
   * See `BarCalendar.isAligned`.
   * @param timeframe Bar resolution.
   * @param tsMs Time.
   * @return Whether aligned.
   */
  isAligned(timeframe: Timeframe, tsMs: number): boolean {
    return floorToTimeframe(timeframe, tsMs) === tsMs;
  }

  /**
   * See `BarCalendar.lastClosedStart` (engine
   * `timeframes.last_closed_start`).
   * @param timeframe Bar resolution.
   * @param asOfMs Evaluation time.
   * @return Bar start or null.
   */
  lastClosedStart(timeframe: Timeframe, asOfMs: number): number | null {
    const previous = shiftTimeframe(
      timeframe,
      floorToTimeframe(timeframe, asOfMs),
      -1
    );
    return previous < 0 ? null : previous;
  }

  /**
   * Always open.
   * @param _tsMs Ignored.
   * @return True.
   */
  isOpen(_tsMs: number): boolean {
    return true;
  }

  /**
   * A continuous market has no sessions.
   * @param _fromMs Ignored.
   * @param _toMs Ignored.
   * @return Empty list.
   */
  sessions(_fromMs: number, _toMs: number): TradingSession[] {
    return [];
  }

  /**
   * Engine `Timeframe.contains`.
   * @param big Higher timeframe.
   * @param small Lower timeframe.
   * @return Whether `small` tiles `big`.
   */
  contains(big: Timeframe, small: Timeframe): boolean {
    const bigMs = TIMEFRAME_MS[big];
    const smallMs = TIMEFRAME_MS[small];
    if (smallMs >= bigMs) return false;
    if (big === '1w' || big === '1M') return DAY_MS % smallMs === 0;
    return bigMs % smallMs === 0;
  }
}

/** Calendar of `24x7` markets (today's UTC-aligned bars, unchanged). */
export const CONTINUOUS_CALENDAR: BarCalendar = new ContinuousCalendar();

// Time zones --------------------------------------------------------------

/** Wall-clock parts of an instant in a time zone. */
export interface ZonedParts {
  /** Year. */
  year: number;
  /** Month 1-12. */
  month: number;
  /** Day of month. */
  day: number;
  /** Hour 0-23. */
  hour: number;
  /** Minute. */
  minute: number;
  /** Second. */
  second: number;
}

/** Cached formatters per time zone. */
const FORMATTERS = new Map<string, Intl.DateTimeFormat>();

/**
 * Wall-clock parts of an instant in a time zone.
 * @param tsMs UTC epoch milliseconds.
 * @param timeZone IANA time zone.
 * @return Parts.
 */
export function zonedParts(tsMs: number, timeZone: string): ZonedParts {
  let format = FORMATTERS.get(timeZone);
  if (!format) {
    format = new Intl.DateTimeFormat('en-US', {
      timeZone,
      hourCycle: 'h23',
      year: 'numeric',
      month: 'numeric',
      day: 'numeric',
      hour: 'numeric',
      minute: 'numeric',
      second: 'numeric',
    });
    FORMATTERS.set(timeZone, format);
  }
  const parts: Record<string, number> = {};
  for (const part of format.formatToParts(new Date(tsMs))) {
    if (part.type !== 'literal') parts[part.type] = Number(part.value);
  }
  return {
    year: parts.year ?? 1970,
    month: parts.month ?? 1,
    day: parts.day ?? 1,
    hour: (parts.hour ?? 0) % 24,
    minute: parts.minute ?? 0,
    second: parts.second ?? 0,
  };
}

/**
 * Offset of a time zone from UTC at an instant.
 * @param tsMs UTC epoch milliseconds.
 * @param timeZone IANA time zone.
 * @return Milliseconds to add to UTC to get the wall clock.
 */
function zoneOffsetMs(tsMs: number, timeZone: string): number {
  const p = zonedParts(tsMs, timeZone);
  const wall = Date.UTC(p.year, p.month - 1, p.day, p.hour, p.minute, p.second);
  return wall - Math.floor(tsMs / 1000) * 1000;
}

/**
 * Local day number (days since 1970-01-01) of an instant in a time zone.
 * @param tsMs UTC epoch milliseconds.
 * @param timeZone IANA time zone.
 * @return Day number.
 */
export function localDayNumber(tsMs: number, timeZone: string): number {
  const p = zonedParts(tsMs, timeZone);
  return Date.UTC(p.year, p.month - 1, p.day) / DAY_MS;
}

/**
 * UTC instant of a local wall time.
 * @param dayNumber Local day number (days since 1970-01-01).
 * @param minuteOfDay Minutes after local midnight.
 * @param timeZone IANA time zone.
 * @return UTC epoch milliseconds.
 */
export function zonedTimeToUtc(
  dayNumber: number,
  minuteOfDay: number,
  timeZone: string
): number {
  const wall = dayNumber * DAY_MS + minuteOfDay * MINUTE_MS;
  let guess = wall - zoneOffsetMs(wall, timeZone);
  // A second pass settles instants next to a daylight-saving change.
  guess = wall - zoneOffsetMs(guess, timeZone);
  return guess;
}

/**
 * ISO date text of a day number.
 * @param dayNumber Days since 1970-01-01.
 * @return `YYYY-MM-DD`.
 */
export function dayText(dayNumber: number): string {
  return new Date(dayNumber * DAY_MS).toISOString().slice(0, 10);
}

/**
 * Day number of ISO date text.
 * @param text `YYYY-MM-DD`.
 * @return Days since 1970-01-01, or NaN for invalid text.
 */
export function dayNumberOf(text: string): number {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(text)) return NaN;
  return Date.parse(`${text}T00:00:00Z`) / DAY_MS;
}

/**
 * Weekday of a day number (0 = Sunday … 6 = Saturday).
 * @param dayNumber Days since 1970-01-01 (a Thursday).
 * @return Weekday.
 */
export function weekdayOf(dayNumber: number): number {
  return (((dayNumber + 4) % 7) + 7) % 7;
}

// Exchange calendars -------------------------------------------------------

/** One materialized session (internal). */
interface Slot {
  /** Local day number. */
  readonly day: number;
  /** Open (UTC ms). */
  readonly openMs: number;
  /** Exclusive close (UTC ms). */
  readonly closeMs: number;
}

/** Time window `[fromMs, toMs)`. */
export interface TimeWindow {
  /** Inclusive start (UTC ms). */
  fromMs: number;
  /** Exclusive end (UTC ms). */
  toMs: number;
}

/** Inputs of a session calendar. */
export interface SessionCalendarOptions {
  /** Authoritative sessions (any order; duplicates by day are merged). */
  sessions?: readonly TradingSession[];
  /**
   * Windows the sessions describe completely (`SessionList` `from_ms` /
   * `to_ms`): a day inside one without a listed session is closed.
   */
  coverage?: readonly TimeWindow[];
  /**
   * Session of a day the list does not cover (default: the regular hours on
   * weekdays). The DEMO provider passes its exchange rules here.
   * @param day Local day number.
   * @return Session or null when closed.
   */
  fallback?: (day: number) => TradingSession | null;
}

/**
 * Exchange calendar answering from a session list where it has one and
 * from the regular weekday hours elsewhere (engine `ExchangeCalendar`).
 */
export class SessionCalendar implements BarCalendar {
  readonly continuous = false;
  readonly id: ExchangeCalendarId;
  readonly timeZone: string;
  private readonly listed = new Map<number, Slot>();
  /** Inclusive local day ranges the list describes completely. */
  private readonly known: [number, number][] = [];
  private readonly byDay = new Map<number, Slot | null>();
  /** Contiguous materialized days `[lo, hi]` and their sessions. */
  private timeline: Slot[] = [];
  private lo = 0;
  private hi = -1;
  private fromMs = 0;
  private toMs = 0;
  private readonly fallback: ((day: number) => TradingSession | null) | null;

  /**
   * Creates the calendar.
   * @param hours Regular hours (time zone, open, close, close grace).
   * @param options Session list and the windows it covers.
   */
  constructor(
    readonly hours: ExchangeHours,
    options: SessionCalendarOptions = {}
  ) {
    this.id = hours.calendar;
    this.timeZone = hours.timeZone;
    this.fallback = options.fallback ?? null;
    for (const session of options.sessions ?? []) {
      const day = dayNumberOf(session.day);
      if (!Number.isFinite(day) || session.close_ms <= session.open_ms)
        continue;
      this.listed.set(day, {
        day,
        openMs: session.open_ms,
        closeMs: session.close_ms,
      });
    }
    for (const window of options.coverage ?? []) {
      if (window.toMs <= window.fromMs) continue;
      let first = localDayNumber(window.fromMs, this.timeZone);
      if (zonedTimeToUtc(first, 0, this.timeZone) < window.fromMs) first += 1;
      let last = localDayNumber(window.toMs - 1, this.timeZone);
      if (zonedTimeToUtc(last + 1, 0, this.timeZone) > window.toMs) last -= 1;
      if (last >= first) this.known.push([first, last]);
    }
  }

  /**
   * Whether the session list describes a local day.
   * @param day Local day number.
   * @return True when listed or inside a covered window.
   */
  covers(day: number): boolean {
    return (
      this.listed.has(day) ||
      this.known.some(([first, last]) => day >= first && day <= last)
    );
  }

  /**
   * Session of a local day (list first, else the weekday rule).
   * @param day Local day number.
   * @return Session or null when closed.
   */
  private slot(day: number): Slot | null {
    const cached = this.byDay.get(day);
    if (cached !== undefined) return cached;
    let result: Slot | null = this.listed.get(day) ?? null;
    if (!result && !this.covers(day) && this.fallback) {
      const ruled = this.fallback(day);
      result =
        ruled && ruled.close_ms > ruled.open_ms
          ? {day, openMs: ruled.open_ms, closeMs: ruled.close_ms}
          : null;
    } else if (!result && !this.covers(day)) {
      const weekday = weekdayOf(day);
      if (weekday >= 1 && weekday <= 5) {
        result = {
          day,
          openMs: zonedTimeToUtc(day, this.hours.openMinute, this.timeZone),
          closeMs: zonedTimeToUtc(day, this.hours.closeMinute, this.timeZone),
        };
      }
    }
    this.byDay.set(day, result);
    return result;
  }

  /**
   * Session on a local date.
   * @param text Exchange-local date `YYYY-MM-DD`.
   * @return Session, or null when the market is closed.
   */
  sessionOnDay(text: string): TradingSession | null {
    const day = dayNumberOf(text);
    if (!Number.isFinite(day)) return null;
    const found = this.slot(day);
    return found ? toSession(found) : null;
  }

  /**
   * Extends the materialized timeline to include a day.
   * @param day Local day number.
   */
  private materialize(day: number): void {
    if (this.hi < this.lo) {
      this.lo = day - TIMELINE_PAD_DAYS;
      this.hi = day + TIMELINE_PAD_DAYS;
      this.rebuild();
      return;
    }
    if (day >= this.lo && day <= this.hi) return;
    if (day < this.lo) this.lo = day - TIMELINE_PAD_DAYS;
    else this.hi = day + TIMELINE_PAD_DAYS;
    this.rebuild();
  }

  /** Rebuilds the timeline array and its millisecond bounds. */
  private rebuild(): void {
    const slots: Slot[] = [];
    for (let day = this.lo; day <= this.hi; day += 1) {
      const found = this.slot(day);
      if (found) slots.push(found);
    }
    this.timeline = slots;
    this.fromMs = zonedTimeToUtc(this.lo, 0, this.timeZone);
    this.toMs = zonedTimeToUtc(this.hi + 1, 0, this.timeZone);
  }

  /**
   * Ensures the timeline holds `tsMs` with `MAX_SCAN_DAYS` days around it.
   * @param tsMs UTC epoch milliseconds.
   */
  private reach(tsMs: number): void {
    const margin = MAX_SCAN_DAYS * DAY_MS;
    if (
      this.hi >= this.lo &&
      tsMs - margin >= this.fromMs &&
      tsMs + margin < this.toMs
    )
      return;
    const day = localDayNumber(tsMs, this.timeZone);
    this.materialize(day - MAX_SCAN_DAYS);
    this.materialize(day + MAX_SCAN_DAYS);
  }

  /**
   * Index of the last timeline session opening at or before a time.
   * @param tsMs Time (inside the timeline).
   * @return Index or -1.
   */
  private indexAtOrBefore(tsMs: number): number {
    let low = 0;
    let high = this.timeline.length - 1;
    let found = -1;
    while (low <= high) {
      const mid = (low + high) >> 1;
      if ((this.timeline[mid]?.openMs ?? Infinity) <= tsMs) {
        found = mid;
        low = mid + 1;
      } else {
        high = mid - 1;
      }
    }
    return found;
  }

  /**
   * Latest session that opened at or before a time.
   * @param tsMs UTC epoch milliseconds.
   * @return Session.
   * @throws {RangeError} When no session opened within the scan window.
   */
  private sessionAtOrBefore(tsMs: number): Slot {
    this.reach(tsMs);
    const found = this.timeline[this.indexAtOrBefore(tsMs)];
    if (!found || tsMs - found.openMs > MAX_SCAN_DAYS * DAY_MS) {
      throw new RangeError(`${this.id} has no session at or before ${tsMs}`);
    }
    return found;
  }

  /**
   * Session after another.
   * @param current Session.
   * @return Next session.
   * @throws {RangeError} When none follows within the scan window.
   */
  private next(current: Slot): Slot {
    this.materialize(current.day + MAX_SCAN_DAYS);
    const index = this.indexAtOrBefore(current.openMs);
    const found = this.timeline[index + 1];
    if (!found || found.day - current.day > MAX_SCAN_DAYS) {
      throw new RangeError(`${this.id} has no session after ${current.day}`);
    }
    return found;
  }

  /**
   * Session before another.
   * @param current Session.
   * @return Previous session.
   * @throws {RangeError} When none precedes within the scan window.
   */
  private previous(current: Slot): Slot {
    this.materialize(current.day - MAX_SCAN_DAYS);
    const index = this.indexAtOrBefore(current.openMs);
    const found = this.timeline[index - 1];
    if (!found || current.day - found.day > MAX_SCAN_DAYS) {
      throw new RangeError(`${this.id} has no session before ${current.day}`);
    }
    return found;
  }

  /**
   * Session containing a time, or the next one.
   * @param tsMs UTC epoch milliseconds.
   * @return Session with `closeMs > tsMs`.
   */
  private firstFrom(tsMs: number): Slot {
    const found = this.sessionAtOrBefore(tsMs);
    return tsMs < found.closeMs ? found : this.next(found);
  }

  /**
   * Session in progress at a time.
   * @param tsMs UTC epoch milliseconds.
   * @return Session, or null between sessions.
   */
  sessionAt(tsMs: number): TradingSession | null {
    const found = this.sessionAtOrBefore(tsMs);
    return tsMs < found.closeMs ? toSession(found) : null;
  }

  /**
   * Session in progress at a time, or the next one to open.
   * @param tsMs UTC epoch milliseconds.
   * @return Session.
   */
  currentOrNext(tsMs: number): TradingSession {
    return toSession(this.firstFrom(tsMs));
  }

  /**
   * First session opening strictly after a time.
   * @param tsMs UTC epoch milliseconds.
   * @return Session.
   */
  nextOpen(tsMs: number): TradingSession {
    const found = this.firstFrom(tsMs);
    return toSession(found.openMs > tsMs ? found : this.next(found));
  }

  /**
   * Last session that closed at or before a time.
   * @param tsMs UTC epoch milliseconds.
   * @return Session.
   */
  lastClosed(tsMs: number): TradingSession {
    const found = this.sessionAtOrBefore(tsMs);
    return toSession(found.closeMs <= tsMs ? found : this.previous(found));
  }

  /**
   * See `BarCalendar.isOpen`.
   * @param tsMs Time.
   * @return Whether in session.
   */
  isOpen(tsMs: number): boolean {
    try {
      return tsMs < this.sessionAtOrBefore(tsMs).closeMs;
    } catch {
      return false;
    }
  }

  /**
   * See `BarCalendar.sessions`.
   * @param fromMs Start.
   * @param toMs End.
   * @return Sessions.
   */
  sessions(fromMs: number, toMs: number): TradingSession[] {
    const result: TradingSession[] = [];
    if (toMs <= fromMs) return result;
    let current = this.firstFrom(fromMs);
    while (current.openMs < toMs) {
      result.push(toSession(current));
      current = this.next(current);
    }
    return result;
  }

  /**
   * See `BarCalendar.contains` (engine `ExchangeCalendar.contains`).
   * @param big Higher timeframe.
   * @param small Lower timeframe.
   * @return Whether they tile.
   */
  contains(big: Timeframe, small: Timeframe): boolean {
    if (TIMEFRAME_MS[small] >= TIMEFRAME_MS[big]) return false;
    if (big === '1M') return small !== '1w';
    if (PERIODIC.has(big)) return true;
    return TIMEFRAME_MS[big] % TIMEFRAME_MS[small] === 0;
  }

  /**
   * Intraday bars in a session (the last one may be short).
   * @param timeframe Intraday timeframe.
   * @param session Session.
   * @return Bar count.
   */
  private count(timeframe: Timeframe, session: Slot): number {
    return Math.ceil(
      (session.closeMs - session.openMs) / TIMEFRAME_MS[timeframe]
    );
  }

  /**
   * Grouping key of a periodic bar.
   * @param timeframe `1d`, `1w` or `1M`.
   * @param day Local day number.
   * @return Key shared by all sessions of one bar.
   */
  private periodKey(timeframe: Timeframe, day: number): number {
    if (timeframe === '1d') return day;
    if (timeframe === '1w') return day - ((weekdayOf(day) + 6) % 7);
    const date = new Date(day * DAY_MS);
    return date.getUTCFullYear() * 12 + date.getUTCMonth();
  }

  /**
   * First session of the periodic bar holding a session.
   * @param timeframe Periodic timeframe.
   * @param session A session of the bar.
   * @return First session.
   */
  private periodFirst(timeframe: Timeframe, session: Slot): Slot {
    const key = this.periodKey(timeframe, session.day);
    let current = session;
    while (timeframe !== '1d') {
      let previous: Slot;
      try {
        previous = this.previous(current);
      } catch {
        break;
      }
      if (this.periodKey(timeframe, previous.day) !== key) break;
      current = previous;
    }
    return current;
  }

  /**
   * Last session of the periodic bar holding a session.
   * @param timeframe Periodic timeframe.
   * @param session A session of the bar.
   * @return Last session.
   */
  private periodLast(timeframe: Timeframe, session: Slot): Slot {
    const key = this.periodKey(timeframe, session.day);
    let current = session;
    while (timeframe !== '1d') {
      const following = this.next(current);
      if (this.periodKey(timeframe, following.day) !== key) break;
      current = following;
    }
    return current;
  }

  /**
   * See `BarCalendar.floor`.
   * @param timeframe Bar resolution.
   * @param tsMs Time.
   * @return Bar start.
   */
  floor(timeframe: Timeframe, tsMs: number): number {
    const found = this.sessionAtOrBefore(tsMs);
    if (PERIODIC.has(timeframe)) {
      return this.periodFirst(timeframe, found).openMs;
    }
    const duration = TIMEFRAME_MS[timeframe];
    const count = this.count(timeframe, found);
    const index =
      tsMs >= found.closeMs + this.hours.closeGraceMs
        ? count - 1
        : Math.min(Math.floor((tsMs - found.openMs) / duration), count - 1);
    return found.openMs + index * duration;
  }

  /**
   * First bar start at or after a time.
   * @param timeframe Bar resolution.
   * @param tsMs Time.
   * @return Session and bar index (periodic: first session, index 0).
   */
  private ceil(timeframe: Timeframe, tsMs: number): [Slot, number] {
    const found = this.firstFrom(tsMs);
    if (PERIODIC.has(timeframe)) {
      const first = this.periodFirst(timeframe, found);
      if (first.openMs >= tsMs) return [first, 0];
      return [this.next(this.periodLast(timeframe, found)), 0];
    }
    if (tsMs <= found.openMs) return [found, 0];
    const index = Math.ceil((tsMs - found.openMs) / TIMEFRAME_MS[timeframe]);
    if (index < this.count(timeframe, found)) return [found, index];
    return [this.next(found), 0];
  }

  /**
   * See `BarCalendar.endOf`.
   * @param timeframe Bar resolution.
   * @param startMs Bar start.
   * @return Bar end.
   */
  endOf(timeframe: Timeframe, startMs: number): number {
    const found = this.sessionAtOrBefore(startMs);
    if (PERIODIC.has(timeframe)) {
      return this.periodLast(timeframe, found).closeMs;
    }
    return Math.min(startMs + TIMEFRAME_MS[timeframe], found.closeMs);
  }

  /**
   * See `BarCalendar.shift`.
   * @param timeframe Bar resolution.
   * @param startMs Bar start or end.
   * @param bars Bars to move.
   * @return Moved bar start.
   */
  shift(timeframe: Timeframe, startMs: number, bars: number): number {
    let [current, index] = this.ceil(timeframe, startMs);
    if (PERIODIC.has(timeframe)) {
      for (let i = 0; i < bars; i += 1) {
        current = this.next(this.periodLast(timeframe, current));
      }
      for (let i = 0; i < -bars; i += 1) {
        current = this.periodFirst(timeframe, this.previous(current));
      }
      return current.openMs;
    }
    index += bars;
    let count = this.count(timeframe, current);
    while (index >= count) {
      index -= count;
      current = this.next(current);
      count = this.count(timeframe, current);
    }
    while (index < 0) {
      current = this.previous(current);
      index += this.count(timeframe, current);
    }
    return current.openMs + index * TIMEFRAME_MS[timeframe];
  }

  /**
   * See `BarCalendar.barsBetween`.
   * @param timeframe Bar resolution.
   * @param startMs Start.
   * @param endMs End.
   * @return Bar count.
   */
  barsBetween(timeframe: Timeframe, startMs: number, endMs: number): number {
    if (endMs <= startMs) return 0;
    let total = 0;
    if (PERIODIC.has(timeframe)) {
      let [current] = this.ceil(timeframe, startMs);
      while (current.openMs < endMs) {
        total += 1;
        current = this.next(this.periodLast(timeframe, current));
      }
      return total;
    }
    const step = TIMEFRAME_MS[timeframe];
    let current = this.firstFrom(startMs);
    while (current.openMs < endMs) {
      const count = this.count(timeframe, current);
      const low = Math.max(startMs, current.openMs) - current.openMs;
      const high = Math.min(endMs - current.openMs, count * step);
      const first = Math.ceil(low / step);
      const last = Math.ceil(high / step) - 1;
      total += Math.max(0, Math.min(last, count - 1) - first + 1);
      current = this.next(current);
    }
    return total;
  }

  /**
   * See `BarCalendar.isAligned`.
   * @param timeframe Bar resolution.
   * @param tsMs Time.
   * @return Whether aligned.
   */
  isAligned(timeframe: Timeframe, tsMs: number): boolean {
    try {
      return this.floor(timeframe, tsMs) === tsMs;
    } catch {
      return false;
    }
  }

  /**
   * See `BarCalendar.lastClosedStart`.
   * @param timeframe Bar resolution.
   * @param asOfMs Evaluation time.
   * @return Bar start or null.
   */
  lastClosedStart(timeframe: Timeframe, asOfMs: number): number | null {
    try {
      const start = this.floor(timeframe, asOfMs);
      if (this.endOf(timeframe, start) <= asOfMs) return start;
      return this.shift(timeframe, start, -1);
    } catch {
      return null;
    }
  }
}

/**
 * Converts a slot to the contract session.
 * @param slot Slot.
 * @return Trading session.
 */
function toSession(slot: Slot): TradingSession {
  return {day: dayText(slot.day), open_ms: slot.openMs, close_ms: slot.closeMs};
}

/**
 * Builds a calendar for an id.
 * @param id Calendar id.
 * @param options Session list and coverage (exchange calendars only).
 * @return Calendar (`CONTINUOUS_CALENDAR` for `24x7`).
 */
export function createBarCalendar(
  id: CalendarId,
  options: SessionCalendarOptions = {}
): BarCalendar {
  return isExchangeCalendar(id)
    ? new SessionCalendar(EXCHANGE_HOURS[id], options)
    : CONTINUOUS_CALENDAR;
}

// Market status -----------------------------------------------------------

/** What the market status badge shows. */
export interface MarketStatus {
  /** Whether the market is in session now. */
  open: boolean;
  /** Session in progress, if any. */
  session: TradingSession | null;
  /** Next session to open (after the current one when open). */
  next: TradingSession | null;
  /** Today's session closes before the regular close. */
  earlyClose: boolean;
  /** Today (exchange-local) is a weekday without a session. */
  holiday: boolean;
  /** Exchange-local date of `nowMs`. */
  localDay: string;
}

/**
 * Market status of a calendar at a time.
 * @param calendar Calendar.
 * @param nowMs Clock.
 * @return Status (always open for `24x7`).
 */
export function marketStatus(
  calendar: BarCalendar,
  nowMs: number
): MarketStatus {
  if (!(calendar instanceof SessionCalendar)) {
    return {
      open: true,
      session: null,
      next: null,
      earlyClose: false,
      holiday: false,
      localDay: dayText(Math.floor(nowMs / DAY_MS)),
    };
  }
  const day = localDayNumber(nowMs, calendar.timeZone);
  const today = calendar.sessionOnDay(dayText(day));
  const weekday = weekdayOf(day);
  const regularClose = zonedTimeToUtc(
    day,
    calendar.hours.closeMinute,
    calendar.timeZone
  );
  let session: TradingSession | null = null;
  let next: TradingSession | null = null;
  try {
    session = calendar.sessionAt(nowMs);
    next = calendar.nextOpen(nowMs);
  } catch {
    // Outside every known session window: report closed without a next open.
  }
  return {
    open: session !== null,
    session,
    next,
    earlyClose: today !== null && today.close_ms < regularClose,
    holiday: today === null && weekday >= 1 && weekday <= 5,
    localDay: dayText(day),
  };
}
